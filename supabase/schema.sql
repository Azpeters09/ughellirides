-- ---------------------------------------------------------------------
-- 1. Enums / status constraints (validated at DB level, not just app)
-- ---------------------------------------------------------------------
create type if not exists registration_status as enum (
  'pending', 'verified', 'active', 'rejected'
);
create type if not exists booking_status as enum (
  'new', 'assigned', 'completed', 'cancelled'
);

-- ---------------------------------------------------------------------
-- 2. Tables
-- ---------------------------------------------------------------------

-- VEHICLES — car/vehicle registrations (vehicle owners)
create table if not exists public.vehicles (
  id                      bigint generated by default as identity primary key,
  owner_name              text not null,
  phone                   text not null,
  email                   text,
  city                    text not null,
  address                 text not null,
  make_model              text not null,
  year                    integer,
  color                   text,
  seats                   text,
  category                text,
  transmission            text,
  plate_number            text not null,
  availability            text,
  license_valid_until     text,
  insurance_valid_until   text,
  roadworthiness_until    text,
  payout_method           text,
  account_details         text,
  created_at              timestamptz not null default now(),
  status                  registration_status not null default 'pending'
);

-- DRIVERS — driver applications
create table if not exists public.drivers (
  id                      bigint generated by default as identity primary key,
  full_name               text not null,
  phone                   text not null,
  dob                     text,
  gender                  text,
  city                    text not null,
  address                 text not null,
  experience              text,
  license_class           text,
  license_expiry          text,
  nin_available           text,
  transmission_types      text,
  areas_known             text,
  availability            text,
  payout_method           text,
  account_details         text,
  owns_vehicle            text,
  created_at              timestamptz not null default now(),
  status                  registration_status not null default 'pending'
);

-- BOOKINGS — ride bookings from customers
create table if not exists public.bookings (
  id                      bigint generated by default as identity primary key,
  customer_name           text not null,
  phone                   text not null,
  pickup                  text not null,
  destination             text not null,
  pickup_time             text,
  service_type            text,
  car_preference          text,
  notes                   text,
  created_at              timestamptz not null default now(),
  status                  booking_status not null default 'new'
);

-- ---------------------------------------------------------------------
-- 3. Indexes (lookups the admin console & API will actually run)
-- ---------------------------------------------------------------------
create index if not exists idx_vehicles_created    on public.vehicles (created_at desc);
create index if not exists idx_vehicles_phone       on public.vehicles (phone);
create index if not exists idx_vehicles_plate       on public.vehicles (plate_number);
create index if not exists idx_vehicles_status      on public.vehicles (status);

create index if not exists idx_drivers_created      on public.drivers (created_at desc);
create index if not exists idx_drivers_phone        on public.drivers (phone);
create index if not exists idx_drivers_status       on public.drivers (status);

create index if not exists idx_bookings_created     on public.bookings (created_at desc);
create index if not exists idx_bookings_phone       on public.bookings (phone);
create index if not exists idx_bookings_status      on public.bookings (status);

-- ---------------------------------------------------------------------
-- 4. Row Level Security
--    Architecture: the Express backend talks to Supabase with the
--    SERVICE ROLE key (bypasses RLS). Public forms POST to the backend,
--    NOT directly to Supabase. So we enable RLS and DENY all anon/authenticated
--    access by default — the service role is the only path in.
--    This is the most secure default. If you later add direct browser
--    clients, add explicit INSERT policies for `anon` here.
-- ---------------------------------------------------------------------
alter table public.vehicles enable row level security;
alter table public.drivers  enable row level security;
alter table public.bookings enable row level security;

-- (No policies = default deny for anon & authenticated roles.
--  The service_role key used by the backend bypasses RLS entirely.)

-- ---------------------------------------------------------------------
-- 5. updated_at trigger (nice-to-have; keeps last-touched time if you
--    later add an updated_at column)
-- ---------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

-- =====================================================================
-- Done. Tables: vehicles, drivers, bookings.
-- The Express API (/api/vehicles, /api/drivers, /api/bookings,
