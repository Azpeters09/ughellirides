-- ---------------------------------------------------------------------
-- 6. reset_identity RPC — used by the migration script's --truncate flag
--    to restart the auto-increment sequence after a clean re-run.
-- ---------------------------------------------------------------------
create or replace function public.reset_identity(tbl text)
returns void as $$
begin
  execute format('alter sequence public.%I_id_seq restart with 1', tbl);
end;
$$ language plpgsql;

